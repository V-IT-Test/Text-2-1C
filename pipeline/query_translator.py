def _pick_system_prompt(advanced_prompt: bool, advanced_short: bool) -> str:
    today = _today_literal()
    if advanced_short:
        return SYSTEM_ADVANCED_SHORT.replace("{TODAY}", today)
    if advanced_prompt:
        return SYSTEM_ADVANCED.replace("{TODAY}", today)
    return SYSTEM_BASIC


def translate_with_feedback(
    user_query: str,
    connection_string: str,
    schema_context: str = "",
    advanced_prompt: bool = False,
    advanced_short: bool = False,
    use_cot: bool = False,
    use_query_plan: bool = False,
    use_schema_linking: bool = False,
    use_value_linking: bool = False,
    use_critic: bool = False,
    model: str = "",
    max_iterations: int = 2,
    log_fn=None,
) -> tuple[str, int]:
    """Generate a 1C query and silently auto-correct it using execution errors.

    Returns (final_query, iterations_used).
    """
    from pipeline.executor import execute

    def log(msg):
        if log_fn:
            log_fn(msg)

    system = _pick_system_prompt(advanced_prompt, advanced_short)
    query = translate(user_query, schema_context, advanced_prompt, advanced_short, use_cot, use_query_plan, use_schema_linking, use_value_linking, use_critic, connection_string, model=model, log_fn=log_fn)

    for iteration in range(1, max_iterations + 1):
        log(f"Попытка выполнения #{iteration}...")
        try:
            execute(connection_string, query)
            log(f"Запрос выполнен успешно.")
            return query, iteration
        except Exception as error:
            log(f"Ошибка 1С: {str(error)[:200]}")
            if iteration == max_iterations:
                log("Лимит итераций исчерпан — возвращается последний вариант запроса.")
                break
            log(f"Запрашиваю исправление у LLM (итерация {iteration + 1})...")
            fix_prompt = (
                f"{_build_prompt(user_query, schema_context)}\n\n"
                f"Предыдущая попытка:\n{query}\n\n"
                f"Ошибка выполнения в 1С:\n{error}\n\n"
                "Исправь запрос с учётом ошибки. "
                "Возвращай только текст запроса, без пояснений и markdown."
            )
            kw = {"model": model} if model else {}
            query = ask_llm(fix_prompt, system=system, **kw)

    return query, max_iterations


def translate(
    user_query: str,
    schema_context: str = "",
    advanced_prompt: bool = False,
    advanced_short: bool = False,
    use_cot: bool = False,
    use_query_plan: bool = False,
    use_schema_linking: bool = False,
    use_value_linking: bool = False,
    use_critic: bool = False,
    conn_str: str = "",
    model: str = "",
    log_fn=None,
) -> str:
    def log(msg):
        if log_fn:
            log_fn(msg)

    system = _pick_system_prompt(advanced_prompt, advanced_short)
    prompt_label = "краткий продвинутый" if advanced_short else ("продвинутый" if advanced_prompt else "базовый")
    log(f"Промпт: {prompt_label}")
    log(f"Модель: {model or 'gpt-4o-mini (дефолт)'}")
    expected_calls = (2 if use_query_plan else 1) + (1 if use_schema_linking else 0)
    log(f"Ожидаемых вызовов LLM: {expected_calls}")

    if schema_context:
        if use_schema_linking:
            from pipeline.schema_linker import filter_schema
            schema_context = filter_schema(user_query, schema_context, log_fn=log)
        if use_value_linking and conn_str:
            from pipeline.value_fetcher import enrich_schema_with_values
            schema_context = enrich_schema_with_values(schema_context, conn_str, log_fn=log)
        log("Схема базы передана в LLM.")
    else:
        log("Схема базы не используется.")

    kw = {"model": model} if model else {}
    prompt = _build_prompt(user_query, schema_context)

    if use_query_plan:
        log("Query Plan: генерация плана (шаг 1/2)...")
        plan = ask_llm(_build_prompt(user_query, schema_context), system=_PLAN_SYSTEM, **kw)
        log("Query Plan: генерация запроса по плану (шаг 2/2)...")
        query = ask_llm(f"{prompt}\n\nПлан запроса:\n{plan}", system=system, **kw)
    elif use_cot:
        log("Chain-of-Thought: запрос с пошаговым рассуждением...")
        raw = ask_llm(prompt, system=system + _COT_SUFFIX, **kw)
        query = _extract_query_tag(raw)
    else:
        log("Генерация запроса...")
        query = ask_llm(prompt, system=system, **kw)

    if use_critic:
        from pipeline.critic import review_query
        log("Критик: проверяю запрос...")
        is_ok, critique = review_query(user_query, schema_context, query, model=model or "", log_fn=log)
        if is_ok:
            log("Критик: запрос корректен.")
        else:
            log("Критик: запрашиваю исправление...")
            fix_prompt = (
                f"{prompt}\n\n"
                f"Сгенерированный запрос:\n{query}\n\n"
                f"Замечания критика:\n{critique}\n\n"
                "Исправь запрос с учётом замечаний. "
                "Возвращай только текст запроса, без пояснений и markdown."
            )
            query = ask_llm(fix_prompt, system=system, **kw)
            log("Критик: запрос исправлен.")

    return query
