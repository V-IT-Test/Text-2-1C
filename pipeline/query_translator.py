def _build_prompt(user_query: str, schema_context: str) -> str:
    if schema_context:
        return f"Схема базы данных:\n{schema_context}\n\nЗапрос: {user_query}"
    return user_query


def _extract_query_tag(text: str) -> str:
    """Extract content from <query>...</query>; fallback to full text."""
    import re
    m = re.search(r"<query>(.*?)</query>", text, re.DOTALL)
    return m.group(1).strip() if m else text.strip()


